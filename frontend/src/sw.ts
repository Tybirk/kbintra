/// <reference lib="webworker" />

import {
  cleanupOutdatedCaches,
  matchPrecache,
  precacheAndRoute,
} from "workbox-precaching"

import { NavigationRoute, registerRoute } from "workbox-routing"

declare let self: ServiceWorkerGlobalScope

// Clean up old caches

cleanupOutdatedCaches()

const PAGE_TIMEOUT_MS = 3000

/**
 * A page load, the start page included, goes to the network, so a deploy is
 * live on the next open. Served from the precache, "/" started the previous
 * build, which the version check then reloaded 3 s in. The precached
 * index.html (the same page at every address) is the fallback: offline, the
 * server erroring mid-deploy, or no answer within 3 s. Pages are not kept
 * per address: that stored a copy of every page, file and API answer opened.
 */
async function loadPage(request: Request): Promise<Response> {
  const network = fetch(request)

  network.catch(() => {})

  try {
    const response = await Promise.race([
      network,
      new Promise<undefined>((resolve) => setTimeout(resolve, PAGE_TIMEOUT_MS)),
    ])

    if (response && response.status < 500) return response
  } catch {
    // Offline
  }

  return (await matchPrecache("/index.html")) ?? network
}

// Before the precache route, which would answer "/" itself. The backend's
// addresses (a file or an API answer opened in the window) are left alone.
registerRoute(
  new NavigationRoute(({ request }) => loadPage(request), {
    denylist: [/^\/(api|media|admin|static|ws)(\/|$)/],
  }),
)

// Precache all assets generated by the build

precacheAndRoute(self.__WB_MANIFEST)

// A new version takes over as soon as it is installed, so the precache holds
// the build the server has. Left waiting, it was activated by the version
// check while a newer one installed, and its clean-up deleted the newer one's
// files. A page still on the previous build finds its chunks not yet loaded
// gone; useVersionCheck reloads it when one fails, as it would at its next
// check.

self.addEventListener("install", () => {
  self.skipWaiting()
})

// The per-address page cache of earlier versions.

self.addEventListener("activate", (event: ExtendableEvent) => {
  event.waitUntil(caches.delete("html-cache"))
})

// Handle push notifications

self.addEventListener("push", (event: PushEvent) => {
  // Must call waitUntil synchronously, before any async operations

  const promiseChain = (async () => {
    if (!event.data) {
      console.log("Push event received but no data")

      // Still show a generic notification on iOS

      await self.registration.showNotification("KB Intra", {
        body: "Du har en ny notifikation",
      })

      return
    }

    try {
      const data = event.data.json()

      // Keep options minimal for iOS Safari compatibility

      const options: NotificationOptions = {
        body: data.body || "Du har en ny notifikation",

        data: data.data || {},
      }

      // Collapse notifications per type+url so repeated notifications

      // (e.g. multiple messages in the same conversation) replace each other

      if (data.data?.notification_type) {
        options.tag = data.data.notification_type + (data.data.url || "")
      }

      // Only add icon if not on iOS (can cause issues)

      const isIOS = /iPhone|iPad|iPod/.test(self.navigator?.userAgent || "")

      if (!isIOS && data.icon) {
        options.icon = data.icon
      }

      await self.registration.showNotification(
        data.title || "KB Intra",

        options,
      )
    } catch (error) {
      console.error("Error handling push event:", error)

      // Fallback: show generic notification

      await self.registration.showNotification("KB Intra", {
        body: "Du har en ny notifikation",
      })
    }
  })()

  event.waitUntil(promiseChain)
})

// Handle notification click

self.addEventListener("notificationclick", (event: NotificationEvent) => {
  event.notification.close()

  const notifUrl = event.notification.data?.url || "/"

  // Build absolute URL - notifUrl may be relative (e.g. "/forum/thread/123")

  const absoluteUrl = notifUrl.startsWith("http")
    ? notifUrl
    : self.location.origin + notifUrl

  event.waitUntil(
    self.clients

      .matchAll({ type: "window", includeUncontrolled: true })

      .then(async (clientList) => {
        // Only consider clients within our app's origin, not unrelated browser tabs

        const appClients = clientList.filter((client) =>
          client.url.startsWith(self.location.origin),
        )

        // Post navigate message to ALL existing app clients so the PWA

        // receives it regardless of which window gets focused (Firefox

        // may focus a regular browser tab instead of the PWA window).

        for (const client of appClients) {
          try {
            client.postMessage({ type: "NAVIGATE", url: absoluteUrl })
          } catch {
            // Client may have been closed since matchAll()
          }
        }

        // On Firefox Android, client.focus() brings the Firefox browser window to the
        // foreground (showing a random tab) instead of the PWA standalone window.
        // Skip focus() on Firefox and fall through to openWindow() instead, which
        // will at least navigate Firefox to the correct page.

        const isFirefox =
          self.navigator?.userAgent?.includes("Firefox") ?? false

        if (appClients.length > 0 && !isFirefox) {
          try {
            await appClients[0].focus()
          } catch {
            // focus() may be rejected if the browser doesn't allow it
          }

          return
        }

        // If no existing window, or on Firefox, open/navigate to the target URL.

        if (self.clients.openWindow) {
          return self.clients.openWindow(absoluteUrl)
        }
      }),
  )
})

// Handle push subscription change (when browser refreshes the subscription)

// The SW cannot send authenticated API requests, so we notify the client

// to re-sync via usePushSubscriptionSync (which has access to the JWT).

// If no client is open, the next app open will re-sync automatically.

self.addEventListener("pushsubscriptionchange", (event: ExtendableEvent) => {
  console.log("[SW] Push subscription changed, notifying clients to re-sync")

  event.waitUntil(
    self.clients

      .matchAll({ type: "window", includeUncontrolled: true })

      .then((clients) => {
        for (const client of clients) {
          client.postMessage({ type: "PUSH_SUBSCRIPTION_CHANGED" })
        }
      }),
  )
})
